'use strict';

const mongoose = require('mongoose');

const inventoryAlertSchema = new mongoose.Schema(
  {
    book: { type: mongoose.Schema.Types.ObjectId, ref: 'Book', required: true, index: true },
    bookTitle: { type: String, required: true }, // snapshot for fast listing
    alertType: {
      type: String,
      enum: ['low_stock', 'out_of_stock', 'reorder_needed', 'overstock'],
      required: true,
    },
    currentStock: { type: Number, required: true },
    threshold: { type: Number },
    status: {
      type: String,
      enum: ['open', 'acknowledged', 'resolved', 'ignored'],
      default: 'open',
      index: true,
    },
    message: { type: String },
    acknowledgedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    acknowledgedAt: { type: Date },
    resolvedAt: { type: Date },
    isAutoGenerated: { type: Boolean, default: true },
  },
  { timestamps: true }
);

// One open auto-alert per book+type at a time (avoids duplicate noise).
inventoryAlertSchema.index(
  { book: 1, alertType: 1, status: 1 },
  { unique: true, partialFilterExpression: { status: 'open' } }
);

module.exports = mongoose.models.InventoryAlert || mongoose.model('InventoryAlert', inventoryAlertSchema);
